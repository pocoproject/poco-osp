std::string TestData::createWorkDirectory()
{
	std::string path = Poco::TemporaryFile::tempName();
	Poco::File(path).createDirectories();
	return path;
}


std::string TestData::path(const std::string& fileName)
{
	Poco::Path p(Poco::Environment::get("POCO_BASE"));
	p.makeDirectory();
	p.pushDirectory("BundleSign");
	p.pushDirectory("testsuite");
	p.pushDirectory("data");
	p.setFileName(fileName);
	return p.toString();
}


void TestData::writeBundle(const std::string& path, const std::map<std::string, std::string>& files)
{
	Poco::FileOutputStream ostr(path);
	Poco::Zip::Compress compress(ostr, true);
	for (const auto& file: files)
	{
		std::istringstream istr(file.second);
		compress.addFile(istr, Poco::DateTime(), Poco::Path(file.first, Poco::Path::PATH_UNIX));
	}
	compress.close();
}


void TestData::renameEntry(const std::string& path, const std::string& name, const std::string& newName)
{
	poco_assert (name.size() == newName.size());

	replaceInFile(path, name, newName);
}


void TestData::replaceInFile(const std::string& path, const std::string& text, const std::string& replacement)
{
	Poco::FileInputStream istr(path);
	std::string content;
	Poco::StreamCopier::copyToString(istr, content);
	istr.close();
	Poco::replaceInPlace(content, text, replacement);
	Poco::FileOutputStream ostr(path);
	ostr << content;
}


